%% ---------------- Adding trial identity to trigger --------------
% -------------- importing trialList --------------
filePath = fullfile('D:\DFF_data', subName, subName + ".csv");

T = readtable(filePath);

T = varfun(@string, T);

T.RespProbe = string(T{:,10} == T{:,5});

% all variation
% T.identity = string(T{:,4}) + "_" + ...
