        if contains(EventsMarkers{iCond}, 'cue')
            Epoch = [-0.5,1.5];
            Epoch_baseline = [-0.5,0];
        else
            Epoch = [-0.5,0.5];
            Epoch_baseline = [-0.5,0];
        end
            % Process: Import MEG/EEG: Events
            sFilesEpochs = bst_process('CallProcess', 'process_import_data_event', ...
                {sFilesList(ii).FileName} , [], ...   
                'subjectname',   subName{1}, ... % 1 out of 1
                'condition',     EventsMarkers{iCond}, ...
                'eventname',     EventsMarkers{iCond}, ...
                'timewindow',    [], ...
                'epochtime',     Epoch, ...
                'split',         0, ...
                'createcond',    1, ...
                'ignoreshort',   1, ...
                'usectfcomp',    1, ...
                'usessp',        1, ...
                'freq',          [], ...
                'baseline',      Epoch_baseline, ...
                'blsensortypes', 'MEG, EEG');

            % % average for ERP analysis
